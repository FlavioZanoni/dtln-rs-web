// Copies the built worklet into awful and stamps its content hash into the
// URL awful loads it from. The ?v= query is what lets the service worker
// cache the file forever and still pick up new builds - without it, returning
// users kept the first version they ever downloaded.
//
// Pass a path (or set AWFUL_DIR) if your checkout lives somewhere else:
//   node sync-to-awful.mjs ../some/other/checkout
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const src = fileURLToPath(new URL("./dist/audio-worklet.js", import.meta.url));

const candidates = [
  process.argv[2],
  process.env.AWFUL_DIR,
  fileURLToPath(new URL("../awful.chat/", import.meta.url)),
  fileURLToPath(new URL("../awful2/", import.meta.url)),
  fileURLToPath(new URL("../awful/", import.meta.url)),
].filter(Boolean);

const root = candidates.find((dir) =>
  existsSync(`${dir.replace(/\/?$/, "/")}frontend/public`),
);
if (!root) {
  console.error(
    `Could not find an awful checkout. Looked in:\n  ${candidates.join("\n  ")}\n` +
      `Pass one explicitly: node sync-to-awful.mjs <path-to-checkout>`,
  );
  process.exit(1);
}
const frontend = `${root.replace(/\/?$/, "/")}frontend/`;

const hash = createHash("sha256")
  .update(readFileSync(src))
  .digest("hex")
  .slice(0, 8);

copyFileSync(src, `${frontend}public/audio-worklet.js`);
writeFileSync(
  `${frontend}src/lib/audio/worklet-url.ts`,
  `// Generated by ../dtln/sync-to-awful.mjs ("npm run sync" there) - do not edit.\n` +
    `// The ?v= content hash makes the service worker treat each worklet build\n` +
    `// as a new cache entry instead of serving the first one forever.\n` +
    `export const WORKLET_URL = "/audio-worklet.js?v=${hash}";\n`,
);
console.log(`synced audio-worklet.js (v=${hash}) -> ${frontend}`);
